/* Generates src/components/galaxy/techIcons.ts — official brand SVG paths only.
   Sources: simple-icons (installed temporarily as devDependency), plus three
   brands removed from newer simple-icons, fetched from official/simple-assets:
     - microsoftazure (simple-icons@11), amazonaws (simple-icons@11)
     - Delta Lake symbol extracted from the official delta.io logo SVG
   Run: node scripts/gen_tech_icons.mjs   (then `npm rm simple-icons`)       */

import { writeFileSync, readFileSync } from "node:fs";
import * as si from "simple-icons";

const WANTED = [
  "python", "openjdk", "apachespark", "apachekafka", "databricks", "apacheparquet",
  "docker", "linux", "githubactions", "vercel", "netlify",
  "postgresql", "mysql", "duckdb", "firebase", "neon",
  "springboot", "fastapi", "react", "nextdotjs", "javascript", "git", "github", "tailwindcss",
  "flutter", "android", "expo", "githubcopilot", "huggingface", "kaggle", "googlecolab",
];

function esc(s) {
  return s.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
}

/* extract the delta symbol path (second path of the official delta.io logo) */
function deltaSymbol() {
  const svg = readFileSync("/tmp/delta-lake-official.svg", "utf8");
  const paths = [...svg.matchAll(/<path\b[^>]*?\sd="([^"]+)"/g)];
  const symbol = paths[1][1]; // ~35×35 mark, brand #00ADD4
  return symbol.replace(/\s+/g, " ").trim();
}

const entries = [];
for (const slug of WANTED) {
  const key = "si" + slug[0].toUpperCase() + slug.slice(1);
  const icon = si[key];
  if (!icon) throw new Error("missing slug: " + slug);
  entries.push({ slug, name: icon.title, hex: icon.hex, vbw: 24, vbh: 24, path: esc(icon.path) });
}

/* azure + aws from simple-icons@11 files */
const azureSvg = readFileSync("/tmp/https:__cdn.jsdelivr.net_npm_simple-icons@11_icons_microsoftazure.svg", "utf8");
const awsSvg = readFileSync("/tmp/https:__cdn.jsdelivr.net_npm_simple-icons@11_icons_amazonaws.svg", "utf8");
const grab = (svg) => svg.match(/ d="([^"]+)"/)[1].replace(/\s+/g, " ").trim();
entries.push({ slug: "azure", name: "Microsoft Azure", hex: "0078D4", vbw: 24, vbh: 24, path: esc(grab(azureSvg)) });
entries.push({ slug: "amazonwebservices", name: "Amazon Web Services", hex: "FF9900", vbw: 24, vbh: 24, path: esc(grab(awsSvg)) });
entries.push({ slug: "deltalake", name: "Delta Lake", hex: "00ADD4", vbw: 35, vbh: 36, path: esc(deltaSymbol()) });

entries.sort((a, b) => a.slug.localeCompare(b.slug));

const body = entries
  .map((e) => `  ${e.slug}: { name: ${JSON.stringify(e.name)}, hex: "#${e.hex}", vw: ${e.vbw}, vh: ${e.vbh}, path: \`${e.path}\` },`)
  .join("\n");

const out = `/* ═══════════════════════════════════════════════════════════════
   OFFICIAL TECHNOLOGY ICONS — authentic brand SVG path data.
   Auto-generated by scripts/gen_tech_icons.mjs — do not edit by hand.
   Sources: simple-icons (CC0), simple-icons@11 for Azure/AWS marks,
   and the official Delta Lake symbol extracted from delta.io.
   Single-path logos rendered as SVG/canvas at any size — crisp.
   ═══════════════════════════════════════════════════════════════ */

export interface TechIconDef {
  name: string;
  hex: string;
  vw: number;
  vh: number;
  path: string;
}

export const TECH_ICONS: Record<string, TechIconDef> = {
${body}
};

/** readable brand color for a dark background — lifts near-black marks
    while keeping their hue identity (never a flat generic recolour) */
export function readableHex(hex: string): string {
  const r = parseInt(hex.slice(1, 3), 16) / 255;
  const g = parseInt(hex.slice(3, 5), 16) / 255;
  const b = parseInt(hex.slice(5, 7), 16) / 255;
  const lum = 0.2126 * r + 0.7152 * g + 0.0722 * b;
  if (lum >= 0.16) return hex;
  /* too dark for the deep-black site — lighten, keep hue */
  const max = Math.max(r, g, b), min = Math.min(r, g, b);
  const l = (max + min) / 2;
  const d = max - min || 1;
  const s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
  const h = max === r ? (g - b) / d + (g < b ? 6 : 0) : max === g ? (b - r) / d + 2 : (r - g) / d + 4;
  const nl = 0.78;
  const ns = Math.min(1, s * 1.15);
  const hue = (h * 60) / 360;
  const q = nl < 0.5 ? nl * (1 + ns) : nl + ns - nl * ns;
  const p = 2 * nl - q;
  const t = (tt: number) => {
    let x = tt; if (x < 0) x += 1; if (x > 1) x -= 1;
    if (x < 1 / 6) return p + (q - p) * 6 * x;
    if (x < 1 / 2) return q;
    if (x < 2 / 3) return p + (q - p) * (2 / 3 - x) * 6;
    return p;
  };
  const to = (v: number) => Math.round(Math.min(255, Math.max(0, v * 255))).toString(16).padStart(2, "0");
  return \`#\${to(t(hue + 1 / 3))}\${to(t(hue))}\${to(t(hue - 1 / 3))}\`.toUpperCase();
}
`;

writeFileSync("src/components/galaxy/techIcons.ts", out);
console.log("wrote", entries.length, "icons");
